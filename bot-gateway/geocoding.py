def get_city_coords(city_name: str):
    """Return (lat, lng) tuple for a city, or None if unknown."""
    if not city_name:
        return None
    return CITY_COORDS.get(city_name.lower().strip())


def haversine(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    """Calculate distance in meters between two lat/lng points."""
    R = 6_371_000
    phi1, phi2 = math.radians(lat1), math.radians(lat2)
    dphi = math.radians(lat2 - lat1)
    dlambda = math.radians(lon2 - lon1)
    a = math.sin(dphi / 2) ** 2 + math.cos(phi1) * math.cos(phi2) * math.sin(dlambda / 2) ** 2
    return 2 * R * math.asin(math.sqrt(a))


def format_distance(meters: float) -> str:
    """Format distance for display (e.g. '350 м' or '1.2 км')."""
    if meters < 1000:
        return f"{round(meters / 10) * 10:.0f} м"
    return f"{meters / 1000:.1f} км"
